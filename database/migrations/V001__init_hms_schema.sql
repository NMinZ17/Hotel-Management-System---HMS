BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ----------------------------------------------------------------------------
-- PHÂN HỆ 1: CƠ SỞ VẬT CHẤT VÀ PHÒNG (5 BẢNG)
