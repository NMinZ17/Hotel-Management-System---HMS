CREATE TABLE hotel (
    hotel_id SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(150) NOT NULL,
    address TEXT NOT NULL,
    phone VARCHAR(30) NOT NULL,
    timezone VARCHAR(50) NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
    CONSTRAINT pk_hotel PRIMARY KEY (hotel_id),
    CONSTRAINT ck_hotel_name_nonempty CHECK (LENGTH(TRIM(name)) > 0)
);

CREATE TABLE room_type (
    room_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(80) NOT NULL,
    max_guests SMALLINT NOT NULL,
    base_price NUMERIC(14,2) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_room_type PRIMARY KEY (room_type_id),
    CONSTRAINT uq_room_type_name UNIQUE (name),
    CONSTRAINT ck_room_type_max_guests CHECK (max_guests >= 1),
    CONSTRAINT ck_room_type_base_price CHECK (base_price >= 0)
);

CREATE TABLE amenity (
    amenity_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(80) NOT NULL,
    CONSTRAINT pk_amenity PRIMARY KEY (amenity_id),
    CONSTRAINT uq_amenity_name UNIQUE (name)
);

CREATE TABLE room (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    room_type_id BIGINT NOT NULL,
    room_number VARCHAR(15) NOT NULL,
    floor SMALLINT NOT NULL,
    housekeeping_status VARCHAR(15) NOT NULL DEFAULT 'CLEAN',
    maintenance_status VARCHAR(15) NOT NULL DEFAULT 'OK',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_room PRIMARY KEY (room_id),
    CONSTRAINT fk_room_room_type FOREIGN KEY (room_type_id)
        REFERENCES room_type(room_type_id) ON DELETE RESTRICT,
    CONSTRAINT uq_room_room_number UNIQUE (room_number),
    CONSTRAINT ck_room_floor CHECK (floor >= 0),
    CONSTRAINT ck_room_housekeeping_status CHECK (
        housekeeping_status IN ('CLEAN', 'DIRTY', 'INSPECTED', 'OUT_OF_SERVICE')
    ),
    CONSTRAINT ck_room_maintenance_status CHECK (
        maintenance_status IN ('OK', 'MINOR_ISSUE', 'OUT_OF_ORDER')
    )
);

CREATE TABLE room_amenity (
    room_id BIGINT NOT NULL,
    amenity_id BIGINT NOT NULL,
    CONSTRAINT pk_room_amenity PRIMARY KEY (room_id, amenity_id),
    CONSTRAINT fk_room_amenity_room FOREIGN KEY (room_id)
        REFERENCES room(room_id) ON DELETE CASCADE,
    CONSTRAINT fk_room_amenity_amenity FOREIGN KEY (amenity_id)
        REFERENCES amenity(amenity_id) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- PHÂN HỆ 2: TÀI KHOẢN, PHÂN QUYỀN VÀ CON NGƯỜI (5 BẢNG)
-- ----------------------------------------------------------------------------

CREATE TABLE role (
    role_id SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(15) NOT NULL,
    name VARCHAR(80) NOT NULL,
    CONSTRAINT pk_role PRIMARY KEY (role_id),
    CONSTRAINT uq_role_code UNIQUE (code),
    CONSTRAINT ck_role_code CHECK (
        code IN ('ADMIN', 'RECEPTION', 'HOUSEKEEPING', 'MAINTENANCE', 'ACCOUNTANT', 'GUEST')
    )
);

CREATE TABLE app_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email VARCHAR(254) NOT NULL,
    password_hash TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_app_user PRIMARY KEY (user_id),
    CONSTRAINT uq_app_user_email UNIQUE (email),
    CONSTRAINT ck_app_user_email_format CHECK (POSITION('@' IN email) > 1)
);

CREATE TABLE user_role (
    user_id BIGINT NOT NULL,
    role_id SMALLINT NOT NULL,
    CONSTRAINT pk_user_role PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_role_user FOREIGN KEY (user_id)
        REFERENCES app_user(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_user_role_role FOREIGN KEY (role_id)
        REFERENCES role(role_id) ON DELETE CASCADE
);

CREATE TABLE guest (
    guest_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NULL,
    full_name VARCHAR(120) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    email VARCHAR(254) NULL,
    CONSTRAINT pk_guest PRIMARY KEY (guest_id),
    CONSTRAINT fk_guest_user FOREIGN KEY (user_id)
        REFERENCES app_user(user_id) ON DELETE SET NULL,
    CONSTRAINT uq_guest_user_id UNIQUE (user_id)
);

CREATE TABLE employee (
    employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    full_name VARCHAR(120) NOT NULL,
    job_title VARCHAR(80) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_employee PRIMARY KEY (employee_id),
    CONSTRAINT fk_employee_user FOREIGN KEY (user_id)
        REFERENCES app_user(user_id) ON DELETE RESTRICT,
    CONSTRAINT uq_employee_user_id UNIQUE (user_id)
);

-- ----------------------------------------------------------------------------
-- PHÂN HỆ 3: KHUYẾN MÃI VÀ ĐẶT PHÒNG (5 BẢNG)
-- ----------------------------------------------------------------------------

CREATE TABLE discount (
    discount_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(30) NOT NULL,
    discount_type VARCHAR(10) NOT NULL,
    value NUMERIC(14,2) NOT NULL,
    valid_from DATE NOT NULL,
    valid_to DATE NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_discount PRIMARY KEY (discount_id),
    CONSTRAINT uq_discount_code UNIQUE (code),
    CONSTRAINT ck_discount_type CHECK (discount_type IN ('PERCENT', 'FIXED')),
    CONSTRAINT ck_discount_value CHECK (
        value > 0 AND (discount_type <> 'PERCENT' OR value <= 100)
    ),
    CONSTRAINT ck_discount_valid_dates CHECK (valid_to >= valid_from)
);

CREATE TABLE reservation (
    reservation_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    booked_by_guest_id BIGINT NOT NULL,
    status VARCHAR(15) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelled_at TIMESTAMPTZ NULL,
    note VARCHAR(200) NULL,
    CONSTRAINT pk_reservation PRIMARY KEY (reservation_id),
    CONSTRAINT fk_reservation_guest FOREIGN KEY (booked_by_guest_id)
        REFERENCES guest(guest_id) ON DELETE RESTRICT,
    CONSTRAINT ck_reservation_status CHECK (
        status IN ('PENDING', 'CONFIRMED', 'CHECKED_IN', 'CHECKED_OUT', 'CANCELLED', 'NO_SHOW')
    ),
    CONSTRAINT ck_reservation_cancelled_consistency CHECK (
        (status = 'CANCELLED' AND cancelled_at IS NOT NULL)
        OR (status <> 'CANCELLED' AND cancelled_at IS NULL)
    )
);

CREATE TABLE reservation_room (
    reservation_room_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reservation_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    check_in_date DATE NOT NULL,
    check_out_date DATE NOT NULL,
    adults SMALLINT NOT NULL DEFAULT 1,
    children SMALLINT NOT NULL DEFAULT 0,
    nightly_price NUMERIC(14,2) NOT NULL,
    is_cancelled BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_reservation_room PRIMARY KEY (reservation_room_id),
    CONSTRAINT fk_reservation_room_reservation FOREIGN KEY (reservation_id)
        REFERENCES reservation(reservation_id) ON DELETE CASCADE,
    CONSTRAINT fk_reservation_room_room FOREIGN KEY (room_id)
        REFERENCES room(room_id) ON DELETE RESTRICT,
    CONSTRAINT ck_reservation_room_dates CHECK (check_out_date > check_in_date),
    CONSTRAINT ck_reservation_room_adults CHECK (adults >= 1),
    CONSTRAINT ck_reservation_room_children CHECK (children >= 0),
    CONSTRAINT ck_reservation_room_price CHECK (nightly_price >= 0),
    CONSTRAINT ex_reservation_room_no_overlap EXCLUDE USING gist (
        room_id WITH =,
        daterange(check_in_date, check_out_date, '[)') WITH &&
    ) WHERE (is_cancelled = FALSE)
);

CREATE TABLE reservation_guest (
    reservation_id BIGINT NOT NULL,
    guest_id BIGINT NOT NULL,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_reservation_guest PRIMARY KEY (reservation_id, guest_id),
    CONSTRAINT fk_reservation_guest_reservation FOREIGN KEY (reservation_id)
        REFERENCES reservation(reservation_id) ON DELETE CASCADE,
    CONSTRAINT fk_reservation_guest_guest FOREIGN KEY (guest_id)
        REFERENCES guest(guest_id) ON DELETE CASCADE
);

CREATE TABLE reservation_discount (
    reservation_id BIGINT NOT NULL,
    discount_id BIGINT NOT NULL,
    discount_amount NUMERIC(14,2) NOT NULL,
    CONSTRAINT pk_reservation_discount PRIMARY KEY (reservation_id),
    CONSTRAINT fk_reservation_discount_reservation FOREIGN KEY (reservation_id)
        REFERENCES reservation(reservation_id) ON DELETE CASCADE,
    CONSTRAINT fk_reservation_discount_discount FOREIGN KEY (discount_id)
        REFERENCES discount(discount_id) ON DELETE RESTRICT,
    CONSTRAINT ck_reservation_discount_amount CHECK (discount_amount >= 0)
);

-- ----------------------------------------------------------------------------
-- PHÂN HỆ 4: LƯU TRÚ, TÀI CHÍNH, DỊCH VỤ, VẬN HÀNH & KIỂM TOÁN (13 BẢNG)
-- ----------------------------------------------------------------------------

CREATE TABLE stay (
    stay_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reservation_id BIGINT NOT NULL,
    checked_in_by BIGINT NOT NULL,
    checked_out_by BIGINT NULL,
    actual_check_in TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actual_check_out TIMESTAMPTZ NULL,
    status VARCHAR(15) NOT NULL DEFAULT 'IN_HOUSE',
    CONSTRAINT pk_stay PRIMARY KEY (stay_id),
    CONSTRAINT fk_stay_reservation FOREIGN KEY (reservation_id)
        REFERENCES reservation(reservation_id) ON DELETE RESTRICT,
    CONSTRAINT fk_stay_checked_in_by FOREIGN KEY (checked_in_by)
        REFERENCES employee(employee_id) ON DELETE RESTRICT,
    CONSTRAINT fk_stay_checked_out_by FOREIGN KEY (checked_out_by)
        REFERENCES employee(employee_id) ON DELETE RESTRICT,
    CONSTRAINT uq_stay_reservation_id UNIQUE (reservation_id),
    CONSTRAINT ck_stay_status CHECK (status IN ('IN_HOUSE', 'CHECKED_OUT')),
    CONSTRAINT ck_stay_checkout_time CHECK (
        actual_check_out IS NULL OR actual_check_out >= actual_check_in
    ),
    CONSTRAINT ck_stay_status_consistency CHECK (
        (status = 'CHECKED_OUT' AND actual_check_out IS NOT NULL AND checked_out_by IS NOT NULL)
        OR (status = 'IN_HOUSE' AND actual_check_out IS NULL)
    )
);

CREATE TABLE stay_room (
    stay_room_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    stay_id BIGINT NOT NULL,
    reservation_room_id BIGINT NULL,
    room_id BIGINT NOT NULL,
    assigned_from TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    assigned_to TIMESTAMPTZ NULL,
    CONSTRAINT pk_stay_room PRIMARY KEY (stay_room_id),
    CONSTRAINT fk_stay_room_stay FOREIGN KEY (stay_id)
        REFERENCES stay(stay_id) ON DELETE CASCADE,
    CONSTRAINT fk_stay_room_reservation_room FOREIGN KEY (reservation_room_id)
        REFERENCES reservation_room(reservation_room_id) ON DELETE RESTRICT,
    CONSTRAINT fk_stay_room_room FOREIGN KEY (room_id)
        REFERENCES room(room_id) ON DELETE RESTRICT,
    CONSTRAINT ck_stay_room_interval CHECK (
        assigned_to IS NULL OR assigned_to > assigned_from
    ),
    CONSTRAINT ex_stay_room_no_overlap EXCLUDE USING gist (
        room_id WITH =,
        tstzrange(assigned_from, COALESCE(assigned_to, 'infinity'::timestamptz), '[)') WITH &&
    )
);

CREATE TABLE folio (
    folio_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    stay_id BIGINT NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'OPEN',
    opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ NULL,
    CONSTRAINT pk_folio PRIMARY KEY (folio_id),
    CONSTRAINT fk_folio_stay FOREIGN KEY (stay_id)
        REFERENCES stay(stay_id) ON DELETE CASCADE,
    CONSTRAINT uq_folio_stay_id UNIQUE (stay_id),
    CONSTRAINT ck_folio_status CHECK (status IN ('OPEN', 'CLOSED', 'VOID')),
    CONSTRAINT ck_folio_closed_consistency CHECK (
        (status = 'CLOSED' AND closed_at IS NOT NULL AND closed_at >= opened_at)
        OR (status <> 'CLOSED')
    )
);

CREATE TABLE folio_item (
    folio_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    folio_id BIGINT NOT NULL,
    entry_type VARCHAR(10) NOT NULL,
    description VARCHAR(200) NOT NULL,
    quantity NUMERIC(10,2) NOT NULL DEFAULT 1,
    unit_price NUMERIC(14,2) NOT NULL,
    source_key VARCHAR(120) NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_folio_item PRIMARY KEY (folio_item_id),
    CONSTRAINT fk_folio_item_folio FOREIGN KEY (folio_id)
        REFERENCES folio(folio_id) ON DELETE CASCADE,
    CONSTRAINT ck_folio_item_entry_type CHECK (
        entry_type IN ('CHARGE', 'DISCOUNT', 'TAX', 'ADJUSTMENT')
    ),
    CONSTRAINT ck_folio_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_folio_item_unit_price CHECK (
        (entry_type IN ('CHARGE', 'TAX') AND unit_price >= 0)
        OR (entry_type IN ('DISCOUNT', 'ADJUSTMENT'))
    )
);

CREATE TABLE invoice (
    invoice_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    folio_id BIGINT NOT NULL,
    invoice_number VARCHAR(40) NOT NULL,
    subtotal NUMERIC(14,2) NOT NULL,
    discount_total NUMERIC(14,2) NOT NULL DEFAULT 0,
    tax_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(10) NOT NULL DEFAULT 'ISSUED',
    CONSTRAINT pk_invoice PRIMARY KEY (invoice_id),
    CONSTRAINT fk_invoice_folio FOREIGN KEY (folio_id)
        REFERENCES folio(folio_id) ON DELETE RESTRICT,
    CONSTRAINT uq_invoice_invoice_number UNIQUE (invoice_number),
    CONSTRAINT ck_invoice_amounts CHECK (
        subtotal >= 0 AND discount_total >= 0 AND tax_amount >= 0
    ),
    CONSTRAINT ck_invoice_status CHECK (
        status IN ('DRAFT', 'ISSUED', 'PAID', 'PARTIAL', 'VOID')
    )
);

CREATE TABLE payment (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    invoice_id BIGINT NOT NULL,
    recorded_by BIGINT NOT NULL,
    amount NUMERIC(14,2) NOT NULL,
    method VARCHAR(15) NOT NULL,
    transaction_ref VARCHAR(80) NULL,
    paid_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_payment PRIMARY KEY (payment_id),
    CONSTRAINT fk_payment_invoice FOREIGN KEY (invoice_id)
        REFERENCES invoice(invoice_id) ON DELETE CASCADE,
    CONSTRAINT fk_payment_recorded_by FOREIGN KEY (recorded_by)
        REFERENCES employee(employee_id) ON DELETE RESTRICT,
    CONSTRAINT ck_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_method CHECK (
        method IN ('CASH', 'CARD', 'TRANSFER', 'EWALLET')
    )
);

CREATE TABLE service (
    service_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(120) NOT NULL,
    category VARCHAR(15) NOT NULL,
    unit_price NUMERIC(14,2) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_service PRIMARY KEY (service_id),
    CONSTRAINT uq_service_name UNIQUE (name),
    CONSTRAINT ck_service_category CHECK (
        category IN ('FOOD', 'BEVERAGE', 'LAUNDRY', 'SPA', 'TRANSPORT', 'OTHER')
    ),
    CONSTRAINT ck_service_unit_price CHECK (unit_price >= 0)
);

CREATE TABLE housekeeping_task (
    task_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    room_id BIGINT NOT NULL,
    assigned_to BIGINT NULL,
    scheduled_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ NULL,
    status VARCHAR(15) NOT NULL DEFAULT 'PENDING',
    CONSTRAINT pk_housekeeping_task PRIMARY KEY (task_id),
    CONSTRAINT fk_housekeeping_task_room FOREIGN KEY (room_id)
        REFERENCES room(room_id) ON DELETE CASCADE,
    CONSTRAINT fk_housekeeping_task_employee FOREIGN KEY (assigned_to)
        REFERENCES employee(employee_id) ON DELETE SET NULL,
    CONSTRAINT ck_housekeeping_task_status CHECK (
        status IN ('PENDING', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')
    ),
    CONSTRAINT ck_housekeeping_task_times CHECK (
        completed_at IS NULL OR completed_at >= scheduled_at
    )
);

CREATE TABLE maintenance_ticket (
    ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    room_id BIGINT NOT NULL,
    reported_by BIGINT NOT NULL,
    assigned_to BIGINT NULL,
    description VARCHAR(200) NOT NULL,
    status VARCHAR(15) NOT NULL DEFAULT 'OPEN',
    reported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ NULL,
    CONSTRAINT pk_maintenance_ticket PRIMARY KEY (ticket_id),
    CONSTRAINT fk_maintenance_ticket_room FOREIGN KEY (room_id)
        REFERENCES room(room_id) ON DELETE CASCADE,
    CONSTRAINT fk_maintenance_ticket_reported_by FOREIGN KEY (reported_by)
        REFERENCES employee(employee_id) ON DELETE RESTRICT,
    CONSTRAINT fk_maintenance_ticket_assigned_to FOREIGN KEY (assigned_to)
        REFERENCES employee(employee_id) ON DELETE SET NULL,
    CONSTRAINT ck_maintenance_ticket_status CHECK (
        status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED')
    ),
    CONSTRAINT ck_maintenance_ticket_times CHECK (
        closed_at IS NULL OR closed_at >= reported_at
    )
);

CREATE TABLE service_order (
    service_order_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    stay_room_id BIGINT NOT NULL,
    assigned_to BIGINT NULL,
    status VARCHAR(15) NOT NULL DEFAULT 'PENDING',
    ordered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ NULL,
    CONSTRAINT pk_service_order PRIMARY KEY (service_order_id),
    CONSTRAINT fk_service_order_stay_room FOREIGN KEY (stay_room_id)
        REFERENCES stay_room(stay_room_id) ON DELETE RESTRICT,
    CONSTRAINT fk_service_order_assigned_to FOREIGN KEY (assigned_to)
        REFERENCES employee(employee_id) ON DELETE SET NULL,
    CONSTRAINT ck_service_order_status CHECK (
        status IN ('PENDING', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')
    ),
    CONSTRAINT ck_service_order_times CHECK (
        completed_at IS NULL OR completed_at >= ordered_at
    )
);

CREATE TABLE service_order_item (
    service_order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    service_order_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL,
    quantity NUMERIC(10,2) NOT NULL DEFAULT 1,
    unit_price NUMERIC(14,2) NOT NULL,
    folio_item_id BIGINT NULL,
    CONSTRAINT pk_service_order_item PRIMARY KEY (service_order_item_id),
    CONSTRAINT fk_service_order_item_order FOREIGN KEY (service_order_id)
        REFERENCES service_order(service_order_id) ON DELETE CASCADE,
    CONSTRAINT fk_service_order_item_service FOREIGN KEY (service_id)
        REFERENCES service(service_id) ON DELETE RESTRICT,
    CONSTRAINT fk_service_order_item_folio_item FOREIGN KEY (folio_item_id)
        REFERENCES folio_item(folio_item_id) ON DELETE SET NULL,
    CONSTRAINT ck_service_order_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_service_order_item_unit_price CHECK (unit_price >= 0)
);

CREATE TABLE guest_review (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    stay_id BIGINT NOT NULL,
    guest_id BIGINT NOT NULL,
    rating SMALLINT NOT NULL,
    comment VARCHAR(1000) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_guest_review PRIMARY KEY (review_id),
    CONSTRAINT fk_guest_review_stay FOREIGN KEY (stay_id)
        REFERENCES stay(stay_id) ON DELETE CASCADE,
    CONSTRAINT fk_guest_review_guest FOREIGN KEY (guest_id)
        REFERENCES guest(guest_id) ON DELETE CASCADE,
    CONSTRAINT uq_guest_review_stay_guest UNIQUE (stay_id, guest_id),
    CONSTRAINT ck_guest_review_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE TABLE audit_event (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    actor_user_id BIGINT NULL,
    reservation_id BIGINT NULL,
    service_order_id BIGINT NULL,
    action VARCHAR(40) NOT NULL,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_audit_event PRIMARY KEY (event_id),
    CONSTRAINT fk_audit_event_actor FOREIGN KEY (actor_user_id)
        REFERENCES app_user(user_id) ON DELETE SET NULL,
    CONSTRAINT fk_audit_event_reservation FOREIGN KEY (reservation_id)
        REFERENCES reservation(reservation_id) ON DELETE SET NULL,
    CONSTRAINT fk_audit_event_service_order FOREIGN KEY (service_order_id)
        REFERENCES service_order(service_order_id) ON DELETE SET NULL
);

