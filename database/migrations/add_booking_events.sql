BEGIN;

CREATE TABLE IF NOT EXISTS schema_migrations (
    version VARCHAR(50) NOT NULL PRIMARY KEY,
    description VARCHAR(200) NOT NULL,
    applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 1) Cho phep tu sinh id (bat dau tu 1000 de khong dung id seed)
ALTER TABLE reservation ALTER COLUMN reservation_id
    ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1000);
ALTER TABLE reservation_room ALTER COLUMN reservation_room_id
    ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1000);

-- 2) Rang buoc ngay hop le cho dat phong
ALTER TABLE reservation_room
    ADD CONSTRAINT ck_reservation_room_dates
        CHECK (check_out_date > check_in_date);

-- 3) Bang nhat ky su kien dat/huy phong
CREATE TABLE booking_events (
    event_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT REFERENCES reservation(reservation_id),
    reservation_room_id BIGINT REFERENCES reservation_room(reservation_room_id),
    guest_id BIGINT NOT NULL REFERENCES guest(guest_id),
    room_id BIGINT NOT NULL REFERENCES room(room_id),
    event_type VARCHAR(20) NOT NULL,
    source VARCHAR(20) NOT NULL DEFAULT 'api',
    dataset VARCHAR(20) NOT NULL DEFAULT 'demo',
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_booking_events_type
        CHECK (event_type IN ('CREATED', 'CANCELLED')),
    CONSTRAINT ck_booking_events_dataset
        CHECK (dataset IN ('demo', 'performance'))
);

INSERT INTO schema_migrations (version, description)
